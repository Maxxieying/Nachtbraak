export const STRINGS = { nl, en, es, de, it };

let current = "nl";

export function detectLang() {
  const nav = (navigator.language || "nl").slice(0, 2).toLowerCase();
  return STRINGS[nav] ? nav : "nl";
}

export function setLang(code) {
  current = STRINGS[code] ? code : "nl";
  document.documentElement.lang = current;
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.nl[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function drinkLabel(key, custom) {
  if (key === "custom") return custom || t("d_custom");
  return t("d_" + key);
}

export function fmtDateTime(iso) {
  return new Intl.DateTimeFormat(current, {
    weekday: "short", day: "numeric", month: "short", hour: "2-digit", minute: "2-digit",
  }).format(new Date(iso));
}

export function weekdayShort(day) {
  // 0 = zondag. 2024-01-07 is een zondag.
  return new Intl.DateTimeFormat(current, { weekday: "short" }).format(new Date(2024, 0, 7 + day));
}

export function fmtDuration(totalSeconds) {
  const s = Math.max(0, Math.floor(totalSeconds));
  const d = Math.floor(s / 86400);
  const h = Math.floor((s % 86400) / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  const p = (n) => String(n).padStart(2, "0");
  return (d > 0 ? d + "d " : "") + p(h) + ":" + p(m) + ":" + p(sec);
}
